/** The permissions of ``role`` (an empty set for no role). */
export function permissionsFor(role) {
  return new Set(ROLE_PERMISSIONS[role] ?? []);
}

/** Whether ``actor`` holds every permission of ``target`` (no escalation). */
export function roleCovers(actor, target) {
  const held = permissionsFor(actor);
  return (ROLE_PERMISSIONS[target] ?? []).every((permission) => held.has(permission));
}
